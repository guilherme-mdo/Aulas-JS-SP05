// Exercício 7: Calcule a área de um triângulo de acordo com os dados informados pelo usuário.

alert("Área de triângulo");

let baseTriangulo = parseFloat(prompt("Informe o valor da base do triângulo: "));

let alturaTriangulo = parseFloat(prompt("Informe o valor da altura do triângulo: "));

let areaTriangulo = (baseTriangulo * alturaTriangulo) / 2;

alert("A área total do triângulo é: " + areaTriangulo);